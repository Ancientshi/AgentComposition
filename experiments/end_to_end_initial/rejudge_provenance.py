"""Uniform supplementary blind scoring after detecting provenance/date confusion.

Primary scores stay immutable. No execution, sample, ranking, scoring scale, or
evidence changes. This is a disclosed post-hoc sensitivity evaluation of all runs.
"""
import concurrent.futures
import json
import time
from pathlib import Path

from run_experiment import ROOT, JUDGE_MODEL, api, digest, dump, parse_json

CLARIFICATION = (
    '\nEvidence provenance and time clarification, identical for every submission: '
    'The evaluation date is 2026-09-23. Do not infer a different current date. '
    'Each observation has an explicit mode: native_execution means an actual command ran '
    'in the isolated task container; native_counterpart means a real public service '
    'was queried; llm_simulator means the observation was generated by an LLM simulator; '
    'validation and budget modes report harness errors or limits. Classify each observation '
    'from its mode instead of assuming all observations are synthetic. '
    'Benchmark input data can contain authored examples; that does not mean the observed '
    'file processing or program execution was simulated. Artifacts marked exists=true '
    'were exported from the real container. Independent verifier results came from actual '
    'execution of the original benchmark tests. For a task asking to process supplied '
    'inputs or an offline database, assess correctness against those inputs and requirements; '
    'absence of a separate online lookup is not itself an error unless the user required it. '
    'These provenance facts do not imply that the output is correct. Apply the same rubric '
    'and inspect actual mistakes, missing deliverables, and failed verifier assertions.'
)


def score(trial):
    dest=trial/'judgment_provenance_clarified.json'
    if dest.exists():return json.loads(dest.read_text())
    original=json.loads((trial/'judge_api.request.json').read_text())
    messages=original['messages']
    messages[0]['content']+=CLARIFICATION
    response=api(JUDGE_MODEL,messages,trial/'judge_provenance_clarified_api.json',max_tokens=1800)
    j=parse_json(response['choices'][0]['message'].get('content') or '')
    for key,limit in [('completion',4),('correctness',4),('constraints',2)]:
        assert isinstance(j[key],(int,float)) and 0<=j[key]<=limit and j[key]*2==int(j[key]*2)
    assert sum(j[k] for k in ['completion','correctness','constraints'])==j['total']
    body=json.loads(messages[1]['content'])
    j.update(judge_model=JUDGE_MODEL,blind_payload_sha256=digest(body),
             protocol='posthoc_provenance_clarification_v2',
             clarification_sha256=digest(CLARIFICATION))
    dump(dest,j)
    return j


def main():
    queries=json.loads((ROOT/'queries.json').read_text())
    expected=[ROOT/'trials'/f'{q["sample_id"]}__r{rank:02d}' for q in queries for rank in [1,5,10,15]]
    errors=[];attempted=set();futures={}
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        while True:
            for trial in expected:
                if trial in attempted or not (trial/'judgment.json').exists():continue
                attempted.add(trial)
                futures[pool.submit(score,trial)]=trial
            for future in list(futures):
                if not future.done():continue
                trial=futures.pop(future)
                try:
                    j=future.result();print(json.dumps({'completed':trial.name,'score':j['total']}),flush=True)
                except Exception as e:
                    errors.append({'trial':trial.name,'error':str(e)})
                    print(json.dumps({'error':errors[-1]}),flush=True)
            count=sum((t/'judgment_provenance_clarified.json').exists() for t in expected)
            dump(ROOT/'rejudge_status.json',{'expected':len(expected),'completed':count,'submitted':len(attempted),'errors':errors})
            if len(attempted)==len(expected) and not futures:break
            time.sleep(5)


if __name__=='__main__':main()
